@pytest.mark.sdk
def test_biomarkers_full_runs_under_latency_budget(
    client: TestClient,
    sample_edf: Path,
) -> None:
    """Plan §6 latency budget: <200 ms on a 30-second window for biomarkers.

    The fixture is a 30 s recording. We allow 2× headroom (400 ms) on CI
    runners since they're not always cold-cache-friendly; the strict budget
    holds for production benchmarking.
    """
    response = client.post(
        "/v1/eeg/biomarkers",
        json={
            "session_file": str(sample_edf),
            "biomarker_set": "full",
        },
    )
    assert response.status_code == 200, response.text
    body = response.json()
    assert (
        body["latency_ms"] < 400.0
    ), f"biomarker compute exceeded 2x latency budget: {body['latency_ms']}ms"


def test_biomarkers_rejects_missing_file(client: TestClient) -> None:
    response = client.post(
        "/v1/eeg/biomarkers",
        json={
            "session_file": "/tmp/definitely-does-not-exist.edf",
            "biomarker_set": "spectral",
        },
    )
    assert response.status_code == 404
    body = response.json()
    assert body["detail"]["error"]["code"] == "recording_not_found"


