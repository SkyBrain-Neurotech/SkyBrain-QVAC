"""POST /v1/eeg/biomarkers end-to-end tests.

Every test uses a real EDF generated by the SDK's own CLI — no synthetic data,
no mocked adapter. Tests are skipped at the conftest level if the SDK isn't
installed; if you're seeing them skip in CI, the runner is missing the [sdk]
extra.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from fastapi.testclient import TestClient


@pytest.mark.sdk
def test_biomarkers_spectral_returns_payload(
    client: TestClient,
    sample_edf: Path,
) -> None:
    response = client.post(
        "/v1/eeg/biomarkers",
        json={
            "session_file": str(sample_edf),
            "biomarker_set": "spectral",
            "profile": "skybrain_4ch",
        },
    )
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["modality"] == "eeg"
    assert body["biomarker_set"] == "spectral"
    assert body["kind"] == "features"
    assert isinstance(body["payload"], dict)
    assert len(body["input_sha256"]) == 64
    assert body["latency_ms"] >= 0.0


